#!/usr/bin/env python3
"""
fixture_parity_report.py - Write parity/reports/fixture_parity.md from the step F fixture tests.

Reads parity/browser_out/fixture_parity/<robot>/<scenario>.json (written by parity/e2e/fixtures/*.spec.ts) and lists,
per robot and scenario, every item with its status (PASS / FAIL / PENDING-THRESHOLD / NOT-VALIDATED), then every FAIL
with expected, actual and the fixture path. Robot x scenario pairs with no fixture directory are listed as
"Not yet validated". Usage: fixture_parity_report.py [--title TEXT]
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "parity" / "browser_out" / "fixture_parity"
REPORT = ROOT / "parity" / "reports" / "fixture_parity.md"
ROBOTS = ["tb3_burger", "tb3_waffle", "tb3_waffle_pi"]
SCENARIOS = ["sensors", "slam", "cartographer", "nav_robotis", "nav_robotis_no_initial_pose", "nav2_bringup",
             "nav2_bringup_matrix", "nav2_bringup_matrix_dwb_burger"]
# fixture directory that a scenario's tests read (to tell "not run" from "no fixture")
FIXDIR = {"nav_robotis_no_initial_pose": "nav_robotis/readiness_deadlock_2026-10-17",
          "nav2_bringup_matrix": "nav2_bringup/matrix", "nav2_bringup_matrix_dwb_burger": "nav2_bringup/matrix_dwb_burger"}


def cell(v, n=160):
    s = v if isinstance(v, str) else json.dumps(v)
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= n else s[:n] + " …"


def main():
    title = sys.argv[sys.argv.index("--title") + 1] if "--title" in sys.argv else ""
    data, totals = {}, {}
    for r in ROBOTS:
        for s in SCENARIOS:
            f = OUT / r / f"{s}.json"
            if f.exists():
                data[(r, s)] = json.load(open(f))
    lines = ["# Fixture parity (step F): tb3_burger, tb3_waffle, tb3_waffle_pi", ""]
    if title:
        lines += [title, ""]
    lines += ["Generated by `parity/compare/fixture_parity_report.py` from `parity/browser_out/fixture_parity/` "
              "(written by `parity/e2e/fixtures/*.spec.ts`). Expected values are read from the committed fixtures "
              "by the specs; nothing is hand-copied. Exact items are PASS/FAIL; numeric items have no limit in "
              "`parity/thresholds.yaml` and are PENDING-THRESHOLD with both values; NOT-VALIDATED = no fixture.", ""]
    lines += ["## Summary", "", "| Robot | Scenario | PASS | FAIL | PENDING-THRESHOLD | NOT-VALIDATED | captured |",
              "|---|---|---|---|---|---|---|"]
    missing = []
    for r in ROBOTS:
        for s in SCENARIOS:
            d = data.get((r, s))
            if not d:
                fx = ROOT / "parity" / "fixtures" / r / FIXDIR.get(s, s)
                missing.append((r, s, "no fixture" if not fx.exists() else "fixture exists, test not run"))
                continue
            c = {}
            for row in d["rows"]:
                c[row["status"]] = c.get(row["status"], 0) + 1
                totals[row["status"]] = totals.get(row["status"], 0) + 1
            lines.append(f"| {r} | {s} | {c.get('PASS', 0)} | {c.get('FAIL', 0)} | {c.get('PENDING-THRESHOLD', 0)} | "
                         f"{c.get('NOT-VALIDATED', 0)} | {d['captured'][:19]} |")
    lines += ["", "Totals: " + ", ".join(f"{k} {v}" for k, v in sorted(totals.items())), ""]
    if missing:
        lines += ["## Not yet validated", "", "| Robot | Scenario | Why |", "|---|---|---|"]
        lines += [f"| {r} | {s} | {w} |" for r, s, w in missing]
        lines.append("")
    lines += ["## FAILs (expected vs actual)", ""]
    n = 0
    for (r, s), d in data.items():
        for row in d["rows"]:
            if row["status"] != "FAIL":
                continue
            n += 1
            lines.append(f"{n}. **{r} / {s} – {row['item']}**  ")
            lines.append(f"   expected: `{cell(row['expected'], 400)}`  ")
            lines.append(f"   actual: `{cell(row['actual'], 400)}`  ")
            if row.get("note"):
                lines.append(f"   detail: {cell(row['note'], 700)}  ")
            lines.append(f"   fixture: `{row['fixture']}`")
    if not n:
        lines.append("None.")
    lines += ["", "## All items", ""]
    for (r, s), d in data.items():
        lines += [f"### {r} / {s}", "", "| Item | Status | Expected | Actual | Fixture |", "|---|---|---|---|---|"]
        for row in d["rows"]:
            lines.append(f"| {cell(row['item'], 100)} | {row['status']} | {cell(row['expected'], 90)} | "
                         f"{cell(row['actual'], 90)} | `{row['fixture']}` |")
        lines.append("")
    REPORT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {REPORT}: " + ", ".join(f"{k} {v}" for k, v in sorted(totals.items())))


if __name__ == "__main__":
    main()
