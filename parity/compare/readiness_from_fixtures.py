#!/usr/bin/env python3
"""
readiness_from_fixtures.py - Write public/js/games/fixture-status.js from the step F fixture test results.

A playground readiness check is passed for a robot only when every fixture item it depends on was run and PASSED
(parity/browser_out/fixture_parity/<robot>/<scenario>.json, written by parity/e2e/fixtures/*.spec.ts). A check with
no fixture test, a missing scenario, or any FAIL / NOT-VALIDATED / PENDING-THRESHOLD item stays locked.
  TF    "TF edges" in sensors, slam, cartographer and nav_robotis
  SENS  every sensors item that is not about the camera
  CAM   every camera / image item of sensors, and the fixture says the model has a camera
  SLAM  every slam (slam_toolbox) item
  AMCL  nav_robotis "both lifecycle managers active after the initial pose" and "lifecycle /amcl"
  NAV   nav_robotis lifecycle items, "/cmd_vel type", and every goal status / error_code item
  FIXED_FRAME, FILT, CM, BT, DOCK, NS: no fixture test yet -> locked
Usage: readiness_from_fixtures.py
"""
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "parity" / "browser_out" / "fixture_parity"
OUT = ROOT / "public" / "js" / "games" / "fixture-status.js"
ROBOTS = ["tb3_burger", "tb3_waffle", "tb3_waffle_pi"]
CAMERA = ("camera", "image_raw")


def rows(robot, scenario):
    f = SRC / robot / f"{scenario}.json"
    return json.load(open(f))["rows"] if f.exists() else None


def judge(selected):
    """selected: list of rows or None (scenario not run). -> (passed, n_items, n_not_passed)"""
    if not selected:
        return False, 0, 0
    bad = [r for r in selected if r["status"] != "PASS"]
    return not bad, len(selected), len(bad)


def checks(robot):
    sc = {s: rows(robot, s) for s in ("sensors", "slam", "cartographer", "nav_robotis")}
    out = {}
    tf = [r for s in sc.values() if s for r in s if r["item"] == "TF edges"]
    out["TF"] = judge(tf if all(sc.values()) else None)
    sens = sc["sensors"]
    out["SENS"] = judge([r for r in sens if not any(c in r["item"] for c in CAMERA)] if sens else None)
    cam = [r for r in sens if any(c in r["item"] for c in CAMERA)] if sens else None
    has_cam = bool(sens) and any(r["item"].startswith("camera present") and r["expected"] is True for r in sens)
    out["CAM"] = judge(cam) if has_cam else (False, 0, 0)
    out["SLAM"] = judge(sc["slam"])
    nav = sc["nav_robotis"]
    out["AMCL"] = judge([r for r in nav if r["item"] in ("both lifecycle managers active after the initial pose", "lifecycle /amcl")] if nav else None)
    out["NAV"] = judge([r for r in nav if r["item"].startswith("lifecycle ") or r["item"].startswith("/cmd_vel type")
                        or r["item"].endswith((" status", " error_code"))] if nav else None)
    for k in ("FIXED_FRAME", "FILT", "CM", "BT", "DOCK", "NS"):
        out[k] = (False, 0, 0)
    return {k: {"pass": p, "items": n, "notPassed": b} for k, (p, n, b) in out.items()}


def main():
    status = {r: checks(r) for r in ROBOTS}
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    OUT.write_text(
        "// Generated by parity/compare/readiness_from_fixtures.py from the fixture parity tests (parity/e2e/fixtures,\n"
        "// report parity/reports/fixture_parity.md). Do not edit by hand. A check is passed only when every fixture item\n"
        "// it depends on passed against real ROS 2 Jazzy; everything else keeps its games locked.\n"
        f"export const FIXTURE_STATUS = {json.dumps({'generated': stamp, 'robots': status}, indent=2)};\n")
    for r, c in status.items():
        print(r, " ".join(f"{k}={'PASS' if v['pass'] else 'locked'}" for k, v in c.items()))


if __name__ == "__main__":
    main()
