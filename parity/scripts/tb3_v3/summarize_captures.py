#!/usr/bin/env python3
"""Night 1, Part 2: one page that says what the captures in parity/fixtures/tb3_jazzy_v3/ show. Every number is read
from a capture file (named in the table); nothing is typed in by hand.
Usage: summarize_captures.py  -> parity/fixtures/tb3_jazzy_v3/SUMMARY.md"""
import glob, json, math, os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
F = os.path.join(ROOT, 'parity', 'fixtures', 'tb3_jazzy_v3')
ROBOTS = ['tb3_burger', 'tb3_waffle_pi', 'tb3_waffle']
rel = lambda p: os.path.relpath(p, ROOT)


def rd(p, default=''):
    try: return open(p).read()
    except OSError: return default


def lines(p): return [l for l in rd(p).splitlines() if l.startswith('/')]


def hz(p):
    m = re.findall(r'average rate: ([\d.]+)', rd(p))
    return m[-1] if m else 'none'


def info_sum(p):
    t = rd(p)
    if not t: return 'not captured'
    ty = (re.search(r'^Type: (.+)$', t, re.M) or [0, '?'])[1]
    pubs, subs = [], []
    for blk in re.split(r'\n(?=Node name: )', t)[1:]:
        node = re.search(r'^Node name: (.+)$', blk, re.M).group(1)
        if re.match(r'_?ros2cli|_NODE_NAME_UNKNOWN', node): continue
        k = re.search(r'^Endpoint type: (.+)$', blk, re.M).group(1)
        tt = re.search(r'^Topic type: (.+)$', blk, re.M).group(1).split('/')[-1]
        (pubs if k == 'PUBLISHER' else subs).append(f'{node} ({tt})')
    return f"type {ty}; pub: {', '.join(pubs) or '-'}; sub: {', '.join(subs) or '-'}"


def gz_pose(p):
    m = re.search(r'Pose \[ XYZ \(m\) \] \[ RPY \(rad\) \]:\s*\n\s*\[([^\]]+)\]\s*\n\s*\[([^\]]+)\]', rd(p))
    return [float(x) for x in m.group(1).split()] + [float(x) for x in m.group(2).split()] if m else None


def main():
    L = ['# tb3_jazzy_v3 captures: what they show (Night 1, Part 2)', '',
         'Generated by `python3 parity/scripts/tb3_v3/summarize_captures.py`. This PC: see `README.md` (Nav2 1.3.10 with',
         'nav2_bringup / nav2_route / opennav_docking 1.3.13, gz-sim 8.10, ros_gz 1.0.16/18). World: headless EGL turtlebot3_world',
         '(`parity/scripts/launch/tb3_world_headless.launch.py`), ROS_DOMAIN_ID 61. Every cell names its file.', '']
    a = os.path.join(F, 'A')
    L += ['## A. Packages and NavigateToPose', '',
          f"- `ros2 pkg list` matches (`{rel(a)}/pkg_list_grep.txt`): " + ', '.join(l for l in rd(os.path.join(a, 'pkg_list_grep.txt')).split() if not l.startswith('exit')) + '; `nav2_docking` is not a package on Jazzy.',
          f"- `NavigateToPose` result has `error_msg`: {'yes' if 'string error_msg' in rd(os.path.join(a, 'NavigateToPose.txt')) else 'NO'} (`{rel(a)}/NavigateToPose.txt`).", '']
    L += ['## B. navigation2.launch.py use_sim_time:=True (shipped map)', '',
          '| Robot | snapshot | nodes | topics | services | actions | route / docking / smoother / collision_detector / collision_monitor | lifecycle states (active / inactive / other) |',
          '|---|---|---|---|---|---|---|---|']
    for r in ROBOTS:
        for mode, snap in (('nopose', 'before_pose'), ('nopose', 'after_wait'), ('pose', 'before_pose'), ('pose', 'after_pose')):
            d = os.path.join(F, r, f'nav_{mode}', snap)
            if not os.path.isdir(d): continue
            sp = dict(l.split(': ') for l in rd(os.path.join(d, 'servers_present.txt')).splitlines() if ': ' in l)
            st = rd(os.path.join(d, 'lifecycle_states.txt'))
            act, ina = st.count('active [3]'), st.count('inactive [2]')
            oth = len([l for l in st.splitlines() if l.strip()]) - act - ina
            when = rd(os.path.join(d, 'when.txt')).strip()
            sim = (re.search(r'sim=([\d.]+)', when) or [0, '?'])[1]
            L.append(f"| {r} | `nav_{mode}/{snap}` (sim {sim} s) | {len(rd(os.path.join(d, 'node_list.txt')).split())} | {len(lines(os.path.join(d, 'topic_list_t.txt')))} | {len(lines(os.path.join(d, 'service_list_t.txt')))} | {len(lines(os.path.join(d, 'action_list_t.txt')))} | "
                     + ' / '.join(sp.get(k, '?') for k in ('route_server', 'docking_server', 'smoother_server', 'collision_detector', 'collision_monitor')) + f" | {act} / {ina} / {oth} |")
    L += ['', 'bt_navigator parameters (after the initial pose):', '']
    for r in ROBOTS:
        d = os.path.join(F, r, 'nav_pose', 'after_pose')
        for k in ('error_code_names', 'error_code_name_prefixes'):
            v = rd(os.path.join(d, f'bt_navigator_{k}.txt')).splitlines()
            L.append(f"- {r} `{k}`: {v[0] if v else 'not captured'} (`{rel(d)}/bt_navigator_{k}.txt`)")
    L += ['', 'Bringup without an initial pose (`nav_nopose/timing.txt`, from the Nav2 log stamps and /clock):', '',
          '| Robot | "Checking transform" (sim s) | "Aborting bringup" (sim s) | wait wall s | wait sim s | RTF during the run |', '|---|---|---|---|---|---|']
    for r in ROBOTS:
        t = rd(os.path.join(F, r, 'nav_nopose', 'timing.txt'))
        g = lambda k: (re.search(k + r': wall_epoch=[\d.]+ sim=([\d.]+)', t) or [0, 'not in log'])[1]
        w = re.search(r'wall ([\d.]+) s, sim ([\d.]+) s', t)
        rtf = rd(os.path.join(F, r, 'nav_nopose', 'rtf.json')) or rd(os.path.join(F, r, 'nav_nopose', 'rtf_before.json'))
        L.append(f"| {r} | {g('global_costmap_checking_transform')} | {g('aborting_bringup')} | {w.group(1) if w else 'n/a'} | {w.group(2) if w else 'n/a'} | {(json.loads(rtf).get('rtf') if rtf else 'n/a')} |")
    L += ['', '## C. /cmd_vel chain, teleop, turtlebot3_drive, burger_cam', '', 'During one goal (`nav_pose/goal/`, goal (0.5, 1.45) in the map frame):', '',
          '| Robot | goal result | topic | `ros2 topic info -v` | `ros2 topic hz` (wall) |', '|---|---|---|---|---|']
    for r in ROBOTS:
        g = os.path.join(F, r, 'nav_pose', 'goal')
        res = json.loads(rd(os.path.join(g, 'result.json'), '{}') or '{}')
        for t in ('cmd_vel_nav', 'cmd_vel_smoothed', 'cmd_vel'):
            L.append(f"| {r} | {res.get('status_name', 'n/a')} {res.get('error_code', '')} | /{t} | {info_sum(os.path.join(g, f'topic_info_v_{t}.txt'))} | {hz(os.path.join(g, f'topic_hz_{t}.txt'))} |")
    L += ['', 'Teleop and turtlebot3_drive in turtlebot3_world (`world/motion/`; motion from `gz model -m <model> -p`):', '',
          '| Robot | program | /cmd_vel while it runs | Gazebo x, y before -> after | moved (m) |', '|---|---|---|---|---|']
    for r in ROBOTS + ['tb3_burger_cam']:
        mdir = os.path.join(F, r, 'world', 'motion')
        for prog, pre in (('turtlebot3_teleop teleop_keyboard (w x5)', 'teleop'), ('turtlebot3_gazebo turtlebot3_drive (12 s)', 'drive')):
            b, a2 = gz_pose(os.path.join(mdir, f'{pre}_pose_before.txt')), gz_pose(os.path.join(mdir, f'{pre}_pose_after.txt'))
            mv = f'{math.hypot(a2[0] - b[0], a2[1] - b[1]):.3f}' if b and a2 else 'n/a'
            L.append(f"| {r} | {prog} | {info_sum(os.path.join(mdir, f'{pre}_cmd_vel_info_v.txt'))} | {'n/a' if not b else f'{b[0]:.3f}, {b[1]:.3f}'} -> {'n/a' if not a2 else f'{a2[0]:.3f}, {a2[1]:.3f}'} | {mv} |")
    L += ['', '## D. Sensors and TF (`world/samples/`)', '', '| Robot | RTF | /scan | /imu Hz | /odom Hz | /joint_states Hz | /camera/image_raw Hz | camera_info | TF edges (view_frames) |', '|---|---|---|---|---|---|---|---|---|']
    for r in ROBOTS + ['tb3_burger_cam']:
        s = os.path.join(F, r, 'world', 'samples')
        if not os.path.isdir(s): continue
        rtf = rd(os.path.join(F, r, 'world', 'rtf.json'))
        scan = rd(os.path.join(s, 'scan_summary.txt')).replace('\n', '; ')
        ci = rd(os.path.join(s, 'echo_once_camera_camera_info.txt'))
        cis = f"{(re.search(r'width: (\d+)', ci) or [0, '?'])[1]}x{(re.search(r'height: (\d+)', ci) or [0, '?'])[1]} frame {(re.search(r'frame_id: (\S+)', ci) or [0, '?'])[1]}" if ci else '-'
        gv = sorted(glob.glob(os.path.join(s, 'frames_*.gv')))
        edges = re.findall(r'"([^"]+)" -> "([^"]+)"\[label=" ?Broadcaster: ([^\\]+)\\nAverage rate: ([\d.]+)', rd(gv[-1])) if gv else []
        es = '; '.join(f'{p}->{c} {rt} Hz' for p, c, b, rt in edges) or 'none'
        L.append(f"| {r} | {json.loads(rtf).get('rtf') if rtf else 'n/a'} | {scan or 'n/a'}; {hz(os.path.join(s, 'hz_scan.txt'))} Hz | {hz(os.path.join(s, 'hz_imu.txt'))} | {hz(os.path.join(s, 'hz_odom.txt'))} | {hz(os.path.join(s, 'hz_joint_states.txt'))} | {hz(os.path.join(s, 'hz_camera_image_raw.txt'))} | {cis} | {es} |")
    L += ['', 'Rates are `ros2 topic hz` over 12 s of wall time, so they include the run\'s real-time factor (RTF column).']
    open(os.path.join(F, 'SUMMARY.md'), 'w').write('\n'.join(L) + '\n')
    print('wrote', rel(os.path.join(F, 'SUMMARY.md')))


if __name__ == '__main__':
    main()
