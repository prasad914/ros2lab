// Copies real ROS 2 packages (and the bridge firmware) from hardware/ into the website, so the browser workspace shows
// the very same files.   node tools/embed-packages.mjs
//   public/js/pkg-sources.js     what every visitor's browser gets: goal_pose_gui, and ros2lab_hardware's package files,
//                                launch file, xacro macro, udev rules and generator (no driver or firmware source)
//   functions/hw-sources.json    the C++ driver (src/, include/, test/) and the firmware: served only by the Cloud
//                                Function getHardwareSources, to students with an approved hardware license
// Rerun it after editing anything under hardware/src/goal_pose_gui, hardware/src/ros2lab_hardware or hardware/firmware,
// then deploy hosting AND functions.
import fs from "fs"; import path from "path";
const sources = {
  goal_pose_gui: { root: "hardware/src/goal_pose_gui" },
  ros2lab_hardware: { root: "hardware/src/ros2lab_hardware", gated: /^(src|include|test)\// },
  ros2lab_firmware: { root: "hardware/firmware", only: /^(ros2lab_bridge\/|README\.md$)/, gated: /^ros2lab_bridge\// },
};
const skip = /__pycache__|\.pytest_cache|\.git$/;
const pub = {}, gated = {}, locked = {};
for (const [name, { root, only, gated: g }] of Object.entries(sources)) {
  const files = {}, hidden = {};
  const walk = (d) => {
    for (const f of fs.readdirSync(d).sort()) {
      const full = path.join(d, f), rel = path.relative(root, full).split(path.sep).join("/");
      if (skip.test(f)) continue;
      if (fs.statSync(full).isDirectory()) walk(full);
      else if (!only || only.test(rel)) (g && g.test(rel) ? hidden : files)[rel] = fs.readFileSync(full, "utf8");
    }
  };
  walk(root); pub[name] = files;
  if (Object.keys(hidden).length) { gated[name] = hidden; locked[name] = Object.keys(hidden); }
}
fs.writeFileSync("public/js/pkg-sources.js", `// GENERATED by tools/embed-packages.mjs from hardware/ (do not edit here)
export const PKG_SOURCES = ${JSON.stringify(pub, null, 0)};
// files served only with a hardware license (Cloud Function getHardwareSources): their names, shown as locked
export const LOCKED_SOURCES = ${JSON.stringify(locked, null, 0)};
`);
fs.writeFileSync("functions/hw-sources.json", JSON.stringify(gated));
const n = (o) => Object.values(o).reduce((s, v) => s + Object.keys(v).length, 0);
console.log(`public: ${Object.entries(pub).map(([k, v]) => `${k} ${Object.keys(v).length}`).join(", ")}; licensed only: ${n(gated)} files (${(fs.statSync("functions/hw-sources.json").size / 1024).toFixed(0)} KB)`);
